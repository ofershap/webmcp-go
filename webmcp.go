// Package webmcp lets a Go web app expose tools to in-browser AI agents
// through the WebMCP API (navigator.modelContext.registerTool).
//
// You declare tools in Go with typed input schemas and handlers. webmcp
// serves a registration script and an invoke endpoint; a browser agent
// calling the tool ends up in your Go handler, and its reply goes back to
// the agent.
//
// Compatibility: WebMCP is an Origin Trial in Chrome 149+ and Edge 150+,
// and works in ChatGPT Desktop. It is not on by default anywhere yet; see
// the README for the current official implementation status.
package webmcp

import (
	"encoding/json"
	"fmt"
	"net/http"
	"strings"
	"sync"
)

// Tool is one callable tool: a name, a human/agent-facing description, a
// JSON Schema for its input, and the Go handler that runs when an agent
// executes it in the browser.
type Tool struct {
	Name        string
	Description string
	InputSchema map[string]any
	Handler     func(input json.RawMessage) (any, error)
}

// Mux registers tools and serves the browser-facing endpoints.
type Mux struct {
	mu    sync.RWMutex
	tools []Tool
}

func NewMux() *Mux { return &Mux{} }

// Register adds a tool. The name must match [a-z0-9-] and be unique.
func (m *Mux) Register(t Tool) error {
	if t.Name == "" || strings.Trim(t.Name, "abcdefghijklmnopqrstuvwxyz0123456789-") != "" {
		return fmt.Errorf("webmcp: invalid tool name %q", t.Name)
	}
	if t.Handler == nil {
		return fmt.Errorf("webmcp: tool %q has no handler", t.Name)
	}
	if t.InputSchema == nil {
		t.InputSchema = map[string]any{"type": "object"}
	}
	m.mu.Lock()
	defer m.mu.Unlock()
	for _, e := range m.tools {
		if e.Name == t.Name {
			return fmt.Errorf("webmcp: duplicate tool %q", t.Name)
		}
	}
	m.tools = append(m.tools, t)
	return nil
}

// ServeHTTP routes the two endpoints:
//
//	GET  {prefix}/register.js  - browser script that registers every tool
//	POST {prefix}/invoke/{name} - called by that script's execute()
func (m *Mux) ServeHTTP(prefix string) http.Handler {
	mux := http.NewServeMux()
	mux.HandleFunc("GET "+prefix+"/register.js", m.serveRegisterJS)
	mux.HandleFunc("POST "+prefix+"/invoke/", m.serveInvoke)
	return mux
}

// ScriptTag returns the tag a page includes to register its tools.
func ScriptTag(prefix string) string {
	return fmt.Sprintf(`<script src="%s/register.js" defer></script>`, prefix)
}

type toolDef struct {
	Name        string         `json:"name"`
	Description string         `json:"description"`
	InputSchema map[string]any `json:"inputSchema"`
}

func (m *Mux) snapshot() []Tool {
	m.mu.RLock()
	defer m.mu.RUnlock()
	return append([]Tool(nil), m.tools...)
}

// serveRegisterJS emits a script that registers every tool with
// navigator.modelContext. Each tool's execute() POSTs the agent-supplied
// input to the invoke endpoint and returns the Go handler's result.
func (m *Mux) serveRegisterJS(w http.ResponseWriter, r *http.Request) {
	tools := m.snapshot()
	defs := make([]toolDef, 0, len(tools))
	for _, t := range tools {
		defs = append(defs, toolDef{t.Name, t.Description, t.InputSchema})
	}
	defsJSON, err := json.Marshal(defs)
	if err != nil {
		http.Error(w, "webmcp: marshal tools", http.StatusInternalServerError)
		return
	}
	prefix := strings.TrimSuffix(r.URL.Path, "/register.js")

	var b strings.Builder
	b.WriteString("// Generated by webmcp-go. Registers this page's tools with the WebMCP API.\n")
	b.WriteString("(async () => {\n")
	b.WriteString("  if (!('modelContext' in navigator) && !('modelContext' in document)) return;\n")
	b.WriteString("  const mc = navigator.modelContext || document.modelContext;\n")
	b.WriteString("  const invokeBase = ")
	invokeBase, _ := json.Marshal(prefix + "/invoke/")
	b.Write(invokeBase)
	b.WriteString(";\n  const defs = ")
	b.Write(defsJSON)
	b.WriteString(`;
  for (const d of defs) {
    await mc.registerTool({
      name: d.name,
      description: d.description,
      inputSchema: d.inputSchema,
      async execute(input) {
        const res = await fetch(invokeBase + d.name, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(input ?? {}),
        });
        if (!res.ok) throw new Error('tool ' + d.name + ' failed: ' + res.status);
        return await res.json();
      },
    });
  }
})();
`)
	w.Header().Set("Content-Type", "text/javascript; charset=utf-8")
	w.Header().Set("Cache-Control", "no-cache")
	if _, err := fmt.Fprint(w, b.String()); err != nil {
		return
	}
}

func (m *Mux) serveInvoke(w http.ResponseWriter, r *http.Request) {
	i := strings.LastIndex(r.URL.Path, "/invoke/")
	if i < 0 {
		http.Error(w, "webmcp: missing tool name", http.StatusBadRequest)
		return
	}
	name := r.URL.Path[i+len("/invoke/"):]
	var found *Tool
	for _, t := range m.snapshot() {
		if t.Name == name {
			cpy := t
			found = &cpy
			break
		}
	}
	if found == nil {
		http.Error(w, "webmcp: unknown tool", http.StatusNotFound)
		return
	}
	var input json.RawMessage
	if err := json.NewDecoder(r.Body).Decode(&input); err != nil {
		http.Error(w, "webmcp: bad input json", http.StatusBadRequest)
		return
	}
	out, err := found.Handler(input)
	if err != nil {
		http.Error(w, "webmcp: tool error: "+err.Error(), http.StatusUnprocessableEntity)
		return
	}
	w.Header().Set("Content-Type", "application/json")
	if out == nil {
		if _, err := fmt.Fprint(w, "null"); err != nil {
			return
		}
		return
	}
	if err := json.NewEncoder(w).Encode(out); err != nil {
		http.Error(w, "webmcp: encode result", http.StatusInternalServerError)
	}
}
